(() => {
  const root = document.querySelector("[data-feed-page]");
  if (!root) return;

  const canCreate = root.dataset.canCreate === "true";
  const filterForm = document.getElementById("feedFilterForm");
  const projectFilter = document.getElementById("feedProjectFilter");
  const characterFilter = document.getElementById("feedCharacterFilter");
  const stream = document.getElementById("feedStream");
  const pagination = document.getElementById("feedPagination");
  const composerForm = document.getElementById("feedComposerForm");
  const composerProject = document.getElementById("feedComposerProject");
  const composerCharacter = document.getElementById("feedComposerCharacter");
  const composerDropzone = document.getElementById("feedComposerDropzone");
  const composerBody = document.getElementById("feedComposerBody");
  const composerImageInput = document.getElementById("feedComposerImageInput");
  const attachButton = document.getElementById("feedAttachButton");
  const importUrlButton = document.getElementById("feedImportUrlButton");
  const autoGenerateSoloButton = document.getElementById("feedAutoGenerateSoloButton");
  const autoGenerateDuoButton = document.getElementById("feedAutoGenerateDuoButton");
  const autoGenerateButtons = [autoGenerateSoloButton, autoGenerateDuoButton].filter(Boolean);
  const attachmentPreview = document.getElementById("feedAttachmentPreview");
  const rankingList = document.getElementById("feedRankingList");
  const reloadButton = document.getElementById("feedReloadButton");
  const editModalEl = document.getElementById("feedEditModal");
  const editForm = document.getElementById("feedEditForm");
  const editPostId = document.getElementById("feedEditPostId");
  const editCharacter = document.getElementById("feedEditCharacter");
  const editStatus = document.getElementById("feedEditStatus");
  const editBody = document.getElementById("feedEditBody");
  const editImageInput = document.getElementById("feedEditImageInput");
  const editRemoveImage = document.getElementById("feedEditRemoveImage");
  if (editModalEl && editModalEl.parentElement !== document.body) {
    document.body.appendChild(editModalEl);
  }
  const editModal = editModalEl ? new bootstrap.Modal(editModalEl) : null;
  let projects = [];
  let selectedComposerImage = null;
  let selectedComposerImageUrl = null;
  let importedImageAssetId = null;
  const feedPostBodies = new Map();
  const feedPosts = new Map();
  const collapsedBodyLimit = 420;
  const feedPageSize = 12;
  let currentFeedPage = 1;
  let currentPagination = { page: 1, per_page: feedPageSize, total: 0, total_pages: 1, has_prev: false, has_next: false };

  function escapeText(value) {
    return NovelUI.escape(value || "");
  }

  function formatDate(value) {
    if (!value) return "";
    try {
      return new Intl.DateTimeFormat("ja-JP", { dateStyle: "medium", timeStyle: "short" }).format(new Date(value));
    } catch (_) {
      return value;
    }
  }

  function avatar(post) {
    const character = post.character || {};
    const image = character.thumbnail_asset?.media_url || character.base_asset?.media_url;
    if (image) {
      return `<img src="${escapeText(image)}" alt="${escapeText(character.name)}">`;
    }
    return `<span>${escapeText((character.name || "?").slice(0, 1))}</span>`;
  }

  function postImage(post) {
    if (!post.image_asset?.media_url) return "";
    return `
      <button class="feed-post-image-button" type="button" data-feed-image-url="${escapeText(post.image_asset.media_url)}" data-feed-image-alt="${escapeText(post.character?.name || "Feed image")}">
        <img class="feed-post-image" src="${escapeText(post.image_asset.media_url)}" alt="Feed image">
      </button>
    `;
  }

  function openImageLightbox(url, alt = "Feed image") {
    if (!url) return;
    let overlay = document.querySelector(".feed-image-lightbox");
    if (!overlay) {
      overlay = document.createElement("div");
      overlay.className = "feed-image-lightbox";
      overlay.innerHTML = `
        <button class="feed-image-lightbox-close" type="button" aria-label="閉じる"><i class="bi bi-x-lg"></i></button>
        <img class="feed-image-lightbox-image" alt="">
      `;
      overlay.addEventListener("click", (event) => {
        if (event.target === overlay || event.target.closest(".feed-image-lightbox-close")) {
          overlay.classList.remove("is-open");
        }
      });
      document.body.appendChild(overlay);
    }
    const image = overlay.querySelector(".feed-image-lightbox-image");
    image.src = url;
    image.alt = alt;
    overlay.classList.add("is-open");
  }

  function bodyToHtml(body) {
    return escapeText(body).replace(/\n/g, "<br>");
  }

  function shouldCollapseBody(body) {
    return body.length > collapsedBodyLimit || body.split(/\r?\n/).length > 8;
  }

  function collapsedBody(body) {
    if (body.length <= collapsedBodyLimit) return body;
    return `${body.slice(0, collapsedBodyLimit).trimEnd()}...`;
  }

  function renderPostBody(post) {
    const postId = String(post.id);
    const body = String(post.body || "");
    feedPostBodies.set(postId, body);
    if (!shouldCollapseBody(body)) {
      return `<div class="feed-post-body">${bodyToHtml(body)}</div>`;
    }
    return `
      <div class="feed-post-body is-collapsed" data-feed-body>
        <span class="feed-body-text">${bodyToHtml(collapsedBody(body))}</span>
      </div>
      <button class="feed-expand-button" type="button" data-feed-expand data-post-id="${postId}" data-expanded="false">さらに表示</button>
    `;
  }

  function managementActions(post) {
    if (!post.can_manage) return "";
    return `
      <div class="feed-post-manage">
        <button class="btn btn-sm btn-outline-light feed-post-edit" type="button" data-post-id="${post.id}">
          <i class="bi bi-pencil-square"></i>
          <span>編集</span>
        </button>
        <label class="btn btn-sm btn-outline-light mb-0">
          <i class="bi bi-upload"></i>
          <span>画像アップロード</span>
          <input class="d-none feed-image-upload" type="file" accept="image/png,image/jpeg,image/webp" data-post-id="${post.id}">
        </label>
        <button class="btn btn-sm btn-outline-light feed-image-generate" type="button" data-post-id="${post.id}">
          <i class="bi bi-stars"></i>
          <span>画像生成</span>
        </button>
        <button class="btn btn-sm btn-outline-danger feed-post-delete" type="button" data-post-id="${post.id}">
          <i class="bi bi-trash"></i>
          <span>削除</span>
        </button>
      </div>
    `;
  }

  function renderPost(post) {
    feedPosts.set(String(post.id), post);
    const characterName = post.character?.name || "Unknown";
    const worldTitle = post.project?.title || "World";
    const statusBadge = post.status !== "published" ? `<span class="feed-status-badge">${escapeText(post.status)}</span>` : "";
    return `
      <article class="feed-post-card" data-post-id="${post.id}">
        <div class="feed-post-main">
          <div class="feed-post-head">
            <div class="feed-post-author">
              <div class="feed-post-avatar">${avatar(post)}</div>
              <div>
                <div class="feed-post-name">${escapeText(characterName)}</div>
                <a class="feed-post-world" href="/projects/${post.project_id}/live-chat">${escapeText(worldTitle)}</a>
              </div>
            </div>
            <div class="feed-post-date">${statusBadge}${escapeText(formatDate(post.published_at || post.created_at))}</div>
          </div>
          ${renderPostBody(post)}
          ${postImage(post)}
          <div class="feed-post-footer">
            <button class="feed-like-button ${post.liked_by_me ? "is-liked" : ""}" type="button" data-post-id="${post.id}" data-liked="${post.liked_by_me ? "true" : "false"}">
              <i class="bi ${post.liked_by_me ? "bi-heart-fill" : "bi-heart"}"></i>
              <span>${post.like_count || 0}</span>
            </button>
            ${managementActions(post)}
          </div>
        </div>
      </article>
    `;
  }

  function renderEmpty() {
    stream.innerHTML = `
      <div class="empty-panel">
        <div class="empty-panel-icon"><i class="bi bi-broadcast"></i></div>
        <div>
          <h3>まだ投稿がありません</h3>
          <p>キャラクターの最初のつぶやきを投稿してください。</p>
        </div>
      </div>
    `;
  }

  function rankingAvatar(item) {
    const character = item.character || {};
    const image = character.thumbnail_asset?.media_url || character.base_asset?.media_url;
    if (image) {
      return `<img src="${escapeText(image)}" alt="${escapeText(character.name)}">`;
    }
    return `<span>${escapeText((character.name || "?").slice(0, 1))}</span>`;
  }

  function renderRanking(items) {
    if (!rankingList) return;
    if (!items.length) {
      rankingList.innerHTML = '<div class="feed-ranking-empty">まだランキング対象の投稿がありません。</div>';
      return;
    }
    rankingList.innerHTML = items.map((item) => `
      <a class="feed-ranking-item" href="/projects/${item.project?.id}/live-chat">
        <span class="feed-ranking-rank">${item.rank}</span>
        <span class="feed-ranking-avatar">${rankingAvatar(item)}</span>
        <span class="feed-ranking-main">
          <strong>${escapeText(item.character?.name || "Unknown")}</strong>
          <small>${escapeText(item.project?.title || "World")}</small>
        </span>
        <span class="feed-ranking-count">${item.post_count}</span>
      </a>
    `).join("");
  }

  function renderPagination(info = currentPagination) {
    currentPagination = {
      page: Number(info.page || 1),
      per_page: Number(info.per_page || feedPageSize),
      total: Number(info.total || 0),
      total_pages: Math.max(1, Number(info.total_pages || 1)),
      has_prev: Boolean(info.has_prev),
      has_next: Boolean(info.has_next),
    };
    if (!pagination) return;
    if (currentPagination.total <= currentPagination.per_page) {
      pagination.innerHTML = "";
      pagination.classList.add("d-none");
      return;
    }
    pagination.classList.remove("d-none");
    const page = currentPagination.page;
    const totalPages = currentPagination.total_pages;
    const start = Math.max(1, page - 2);
    const end = Math.min(totalPages, page + 2);
    const pageButtons = [];
    for (let pageNumber = start; pageNumber <= end; pageNumber += 1) {
      pageButtons.push(`
        <button class="feed-page-number ${pageNumber === page ? "is-active" : ""}" type="button" data-feed-page-number="${pageNumber}" ${pageNumber === page ? 'aria-current="page"' : ""}>
          ${pageNumber}
        </button>
      `);
    }
    const firstItem = currentPagination.total ? (page - 1) * currentPagination.per_page + 1 : 0;
    const lastItem = Math.min(currentPagination.total, page * currentPagination.per_page);
    pagination.innerHTML = `
      <div class="feed-pagination-summary">${firstItem}-${lastItem} / ${currentPagination.total}</div>
      <div class="feed-pagination-controls">
        <button class="feed-page-button" type="button" data-feed-page-step="-1" ${currentPagination.has_prev ? "" : "disabled"} aria-label="前のページ">
          <i class="bi bi-chevron-left"></i>
        </button>
        ${start > 1 ? `<button class="feed-page-number" type="button" data-feed-page-number="1">1</button><span class="feed-page-ellipsis">...</span>` : ""}
        ${pageButtons.join("")}
        ${end < totalPages ? `<span class="feed-page-ellipsis">...</span><button class="feed-page-number" type="button" data-feed-page-number="${totalPages}">${totalPages}</button>` : ""}
        <button class="feed-page-button" type="button" data-feed-page-step="1" ${currentPagination.has_next ? "" : "disabled"} aria-label="次のページ">
          <i class="bi bi-chevron-right"></i>
        </button>
      </div>
    `;
  }

  function ensureImageFile(file) {
    if (!file) return false;
    if (!file.type.startsWith("image/")) {
      NovelUI.toast("画像ファイルを選択してください。", "warning");
      return false;
    }
    return true;
  }

  function clearComposerImage() {
    selectedComposerImage = null;
    importedImageAssetId = null;
    if (selectedComposerImageUrl) URL.revokeObjectURL(selectedComposerImageUrl);
    selectedComposerImageUrl = null;
    if (composerImageInput) composerImageInput.value = "";
    if (attachmentPreview) {
      attachmentPreview.classList.add("d-none");
      attachmentPreview.innerHTML = "";
    }
    composerDropzone?.classList.remove("has-attachment");
  }

  function setComposerImage(file) {
    if (!ensureImageFile(file)) return;
    clearComposerImage();
    selectedComposerImage = file;
    selectedComposerImageUrl = URL.createObjectURL(file);
    composerDropzone?.classList.add("has-attachment");
    attachmentPreview.classList.remove("d-none");
    attachmentPreview.innerHTML = `
      <img src="${selectedComposerImageUrl}" alt="添付画像プレビュー">
      <button class="feed-attachment-remove" type="button" id="feedAttachmentRemove" aria-label="添付画像を削除">
        <i class="bi bi-x-lg"></i>
      </button>
    `;
  }

  function setImportedImage(asset) {
    if (!asset?.id || !asset.media_url) return;
    clearComposerImage();
    importedImageAssetId = asset.id;
    composerDropzone?.classList.add("has-attachment");
    attachmentPreview.classList.remove("d-none");
    attachmentPreview.innerHTML = `
      <img src="${escapeText(asset.media_url)}" alt="取り込み画像プレビュー">
      <button class="feed-attachment-remove" type="button" id="feedAttachmentRemove" aria-label="添付画像を削除">
        <i class="bi bi-x-lg"></i>
      </button>
    `;
  }

  function extractFirstUrl(text) {
    const match = String(text || "").match(/https?:\/\/\S+/);
    return match ? match[0].replace(/[)\]。）、,]+$/, "") : "";
  }

  async function loadProjects() {
    projects = await NovelUI.api("/api/v1/projects");
    const options = projects.map((project) => `<option value="${project.id}">${escapeText(project.title)}</option>`).join("");
    projectFilter.insertAdjacentHTML("beforeend", options);
    if (composerProject) composerProject.innerHTML = options;
    const firstProjectId = composerProject?.value || projectFilter.value || projects[0]?.id;
    if (firstProjectId) await loadCharactersForProject(firstProjectId, { target: composerCharacter });
  }

  async function loadCharactersForProject(projectId, { target }) {
    if (!target) return [];
    target.innerHTML = '<option value="">読み込み中...</option>';
    if (!projectId) {
      target.innerHTML = '<option value="">すべて</option>';
      return [];
    }
    const characters = await NovelUI.api(`/api/v1/projects/${projectId}/characters`);
    const prefix = target === characterFilter ? '<option value="">すべて</option>' : "";
    target.innerHTML = prefix + characters.map((character) => `<option value="${character.id}">${escapeText(character.name)}</option>`).join("");
    return characters;
  }

  async function loadFeed(page = currentFeedPage) {
    currentFeedPage = Math.max(1, Number(page || 1));
    const params = new URLSearchParams(new FormData(filterForm));
    [...params.keys()].forEach((key) => {
      if (!params.get(key)) params.delete(key);
    });
    params.set("include_pagination", "1");
    params.set("page", String(currentFeedPage));
    params.set("per_page", String(feedPageSize));
    const suffix = params.toString() ? `?${params.toString()}` : "";
    const payload = await NovelUI.api(`/api/v1/feed/posts${suffix}`);
    const posts = Array.isArray(payload) ? payload : (payload.items || []);
    renderPagination(Array.isArray(payload) ? { page: 1, per_page: posts.length || feedPageSize, total: posts.length, total_pages: 1 } : payload.pagination);
    if (!posts.length) {
      renderEmpty();
      return;
    }
    feedPostBodies.clear();
    feedPosts.clear();
    stream.innerHTML = posts.map(renderPost).join("");
  }

  async function loadRanking() {
    const params = new URLSearchParams();
    params.set("limit", "10");
    if (projectFilter.value) params.set("project_id", projectFilter.value);
    const items = await NovelUI.api(`/api/v1/feed/ranking/characters?${params.toString()}`);
    renderRanking(items);
  }

  async function createPost(event) {
    event.preventDefault();
    const body = Object.fromEntries(new FormData(composerForm).entries());
    const projectId = Number(body.project_id);
    body.character_id = Number(body.character_id);
    if (importedImageAssetId && !selectedComposerImage) {
      body.image_asset_id = importedImageAssetId;
    }
    const previousProjectId = composerProject.value;
    const previousCharacterId = composerCharacter.value;
    try {
      const post = await NovelUI.api(`/api/v1/projects/${projectId}/feed/posts`, { method: "POST", body });
      if (selectedComposerImage) {
        const imageBody = new FormData();
        imageBody.append("file", selectedComposerImage);
        const response = await fetch(`/api/v1/feed/posts/${post.id}/image/upload`, { method: "POST", body: imageBody, credentials: "same-origin" });
        const payload = await response.json().catch(() => ({}));
        if (!response.ok) throw new Error(payload?.data?.message || payload?.message || `HTTP ${response.status}`);
      }
      composerForm.reset();
      clearComposerImage();
      composerProject.value = previousProjectId;
      if (composerProject.value) await loadCharactersForProject(composerProject.value, { target: composerCharacter });
      composerCharacter.value = previousCharacterId;
      NovelUI.toast("Feedに投稿しました。");
      await loadFeed(1);
    } catch (error) {
      NovelUI.toast(error.message || "投稿に失敗しました。", "danger");
    }
  }

  async function autoGenerateFeed(interactionMode = "solo", button = autoGenerateSoloButton) {
    const projectId = Number(composerProject?.value || projectFilter.value);
    if (!projectId) {
      NovelUI.toast("ワールドを選択してください。", "warning");
      return;
    }
    const autoGenerateButton = button || autoGenerateSoloButton || autoGenerateDuoButton;
    const originalHtml = button?.innerHTML || "";
    autoGenerateButtons.forEach((item) => {
      item.disabled = true;
    });
    autoGenerateButton.innerHTML = '<span class="spinner-border spinner-border-sm me-2"></span>生成中...';
    try {
      await NovelUI.api(`/api/v1/projects/${projectId}/feed/generate`, {
        method: "POST",
        body: { count: 1, interaction_mode: interactionMode },
      });
      NovelUI.toast("画像付きFeedを自動生成しました。");
      if (projectFilter.value && Number(projectFilter.value) !== projectId) {
        projectFilter.value = String(projectId);
        await loadCharactersForProject(projectId, { target: characterFilter });
      }
      await loadFeed(1);
      await loadRanking();
    } finally {
      autoGenerateButtons.forEach((item) => {
        item.disabled = false;
      });
      autoGenerateButton.disabled = false;
      autoGenerateButton.innerHTML = originalHtml;
    }
  }

  async function toggleLike(button) {
    const postId = Number(button.dataset.postId);
    const liked = button.dataset.liked === "true";
    const method = liked ? "DELETE" : "POST";
    const post = await NovelUI.api(`/api/v1/feed/posts/${postId}/like`, { method });
    button.dataset.liked = post.liked_by_me ? "true" : "false";
    button.classList.toggle("is-liked", post.liked_by_me);
    button.innerHTML = `<i class="bi ${post.liked_by_me ? "bi-heart-fill" : "bi-heart"}"></i><span>${post.like_count || 0}</span>`;
  }

  async function uploadImage(input) {
    const [file] = input.files || [];
    if (!file) return;
    const postId = Number(input.dataset.postId);
    const body = new FormData();
    body.append("file", file);
    const response = await fetch(`/api/v1/feed/posts/${postId}/image/upload`, { method: "POST", body, credentials: "same-origin" });
    const payload = await response.json().catch(() => ({}));
    if (!response.ok) throw new Error(payload?.data?.message || payload?.message || `HTTP ${response.status}`);
    NovelUI.toast("投稿画像をアップロードしました。");
    await loadFeed();
  }

  async function generateImage(button) {
    const postId = Number(button.dataset.postId);
    button.disabled = true;
    button.innerHTML = '<span class="spinner-border spinner-border-sm me-2"></span>生成中...';
    try {
      await NovelUI.api(`/api/v1/feed/posts/${postId}/image/generate`, { method: "POST", body: {} });
      NovelUI.toast("投稿画像を生成しました。");
      await loadFeed();
    } finally {
      button.disabled = false;
      button.innerHTML = '<i class="bi bi-stars"></i><span>画像生成</span>';
    }
  }

  async function deletePost(button) {
    const postId = Number(button.dataset.postId);
    if (!confirm("この投稿を削除しますか？")) return;
    await NovelUI.api(`/api/v1/feed/posts/${postId}`, { method: "DELETE" });
    NovelUI.toast("投稿を削除しました。");
    await loadFeed();
  }

  async function openEditPost(button) {
    const postId = String(button.dataset.postId);
    const post = feedPosts.get(postId);
    if (!post || !editModal) return;
    editPostId.value = postId;
    editBody.value = post.body || "";
    editStatus.value = post.status || "published";
    await loadCharactersForProject(post.project_id, { target: editCharacter });
    editCharacter.value = String(post.character_id);
    if (editImageInput) editImageInput.value = "";
    if (editRemoveImage) editRemoveImage.checked = false;
    editModal.show();
  }

  async function saveEditedPost(event) {
    event.preventDefault();
    const postId = Number(editPostId.value);
    if (!postId) return;
    const submitButton = editForm.querySelector('button[type="submit"]');
    const originalHtml = submitButton.innerHTML;
    submitButton.disabled = true;
    submitButton.innerHTML = '<span class="spinner-border spinner-border-sm me-2"></span>保存中...';
    try {
      const payload = {
        body: editBody.value,
        character_id: Number(editCharacter.value),
        status: editStatus.value,
      };
      if (editRemoveImage?.checked) {
        payload.image_asset_id = null;
      }
      await NovelUI.api(`/api/v1/feed/posts/${postId}`, {
        method: "PATCH",
        body: payload,
      });
      const [file] = editImageInput?.files || [];
      if (file) {
        const imageBody = new FormData();
        imageBody.append("file", file);
        const response = await fetch(`/api/v1/feed/posts/${postId}/image/upload`, { method: "POST", body: imageBody, credentials: "same-origin" });
        const payload = await response.json().catch(() => ({}));
        if (!response.ok) throw new Error(payload?.data?.message || payload?.message || `HTTP ${response.status}`);
      }
      editModal.hide();
      NovelUI.toast("投稿を更新しました。");
      await loadFeed();
      await loadRanking();
    } finally {
      submitButton.disabled = false;
      submitButton.innerHTML = originalHtml;
    }
  }

  async function importFromUrl() {
    const projectId = Number(composerProject.value);
    if (!projectId) {
      NovelUI.toast("先にワールドを選択してください。", "warning");
      return;
    }
    const url = extractFirstUrl(composerBody.value);
    if (!url) {
      NovelUI.toast("本文にXなどの記事URLを貼ってください。", "warning");
      return;
    }
    importUrlButton.disabled = true;
    importUrlButton.innerHTML = '<span class="spinner-border spinner-border-sm me-2"></span>取り込み中...';
    try {
      const result = await NovelUI.api(`/api/v1/projects/${projectId}/feed/import-url`, {
        method: "POST",
        body: { url },
      });
      if (result.body) {
        composerBody.value = result.body;
      }
      if (result.image_asset) {
        setImportedImage(result.image_asset);
      }
      NovelUI.toast("URLから本文と画像を取り込みました。");
    } finally {
      importUrlButton.disabled = false;
      importUrlButton.innerHTML = '<i class="bi bi-link-45deg"></i><span>URLから取り込む</span>';
    }
  }

  projectFilter.addEventListener("change", async () => {
    await loadCharactersForProject(projectFilter.value, { target: characterFilter });
    await loadFeed(1);
    await loadRanking();
  });
  characterFilter.addEventListener("change", () => loadFeed(1).catch((error) => NovelUI.toast(error.message || "読み込みに失敗しました。", "danger")));
  filterForm.addEventListener("submit", (event) => {
    event.preventDefault();
    loadFeed(1).catch((error) => NovelUI.toast(error.message || "読み込みに失敗しました。", "danger"));
  });
  filterForm.addEventListener("input", (event) => {
    if (event.target.id === "feedSearchInput") {
      clearTimeout(filterForm._timer);
      filterForm._timer = setTimeout(() => loadFeed(1).catch(() => {}), 350);
    }
  });
  reloadButton.addEventListener("click", () => {
    Promise.all([loadFeed(), loadRanking()]).catch((error) => NovelUI.toast(error.message || "読み込みに失敗しました。", "danger"));
  });
  if (composerForm) {
    composerForm.addEventListener("submit", createPost);
    composerProject.addEventListener("change", () => {
      loadCharactersForProject(composerProject.value, { target: composerCharacter }).catch((error) => NovelUI.toast(error.message || "キャラクター取得に失敗しました。", "danger"));
    });
    attachButton?.addEventListener("click", () => composerImageInput?.click());
    importUrlButton?.addEventListener("click", () => {
      importFromUrl().catch((error) => NovelUI.toast(error.message || "URL取り込みに失敗しました。", "danger"));
    });
    autoGenerateSoloButton?.addEventListener("click", () => {
      autoGenerateFeed("solo", autoGenerateSoloButton).catch((error) => NovelUI.toast(error.message || "Feed自動生成に失敗しました。", "danger"));
    });
    autoGenerateDuoButton?.addEventListener("click", () => {
      autoGenerateFeed("duo", autoGenerateDuoButton).catch((error) => NovelUI.toast(error.message || "Feed自動生成に失敗しました。", "danger"));
    });
    composerImageInput?.addEventListener("change", () => setComposerImage(composerImageInput.files?.[0]));
    composerDropzone?.addEventListener("dragenter", (event) => {
      event.preventDefault();
      composerDropzone.classList.add("is-dragover");
    });
    composerDropzone?.addEventListener("dragover", (event) => {
      event.preventDefault();
      composerDropzone.classList.add("is-dragover");
    });
    composerDropzone?.addEventListener("dragleave", (event) => {
      if (!composerDropzone.contains(event.relatedTarget)) {
        composerDropzone.classList.remove("is-dragover");
      }
    });
    composerDropzone?.addEventListener("drop", (event) => {
      event.preventDefault();
      composerDropzone.classList.remove("is-dragover");
      const [file] = event.dataTransfer?.files || [];
      setComposerImage(file);
    });
    attachmentPreview?.addEventListener("click", (event) => {
      if (event.target.closest("#feedAttachmentRemove")) {
        clearComposerImage();
      }
    });
  }
  editForm?.addEventListener("submit", (event) => {
    saveEditedPost(event).catch((error) => NovelUI.toast(error.message || "投稿の更新に失敗しました。", "danger"));
  });
  stream.addEventListener("click", (event) => {
    const likeButton = event.target.closest(".feed-like-button");
    if (likeButton) {
      toggleLike(likeButton).catch((error) => NovelUI.toast(error.message || "いいねに失敗しました。", "danger"));
      return;
    }
    const generateButton = event.target.closest(".feed-image-generate");
    if (generateButton) {
      generateImage(generateButton).catch((error) => NovelUI.toast(error.message || "画像生成に失敗しました。", "danger"));
      return;
    }
    const deleteButton = event.target.closest(".feed-post-delete");
    if (deleteButton) {
      deletePost(deleteButton).catch((error) => NovelUI.toast(error.message || "削除に失敗しました。", "danger"));
      return;
    }
    const editButton = event.target.closest(".feed-post-edit");
    if (editButton) {
      openEditPost(editButton).catch((error) => NovelUI.toast(error.message || "編集画面を開けませんでした。", "danger"));
      return;
    }
    const expandButton = event.target.closest("[data-feed-expand]");
    if (expandButton) {
      const body = expandButton.previousElementSibling;
      if (!body?.matches("[data-feed-body]")) return;
      const fullBody = feedPostBodies.get(String(expandButton.dataset.postId)) || "";
      const isExpanded = expandButton.dataset.expanded === "true";
      body.classList.toggle("is-collapsed", isExpanded);
      body.querySelector(".feed-body-text").innerHTML = bodyToHtml(isExpanded ? collapsedBody(fullBody) : fullBody);
      expandButton.dataset.expanded = isExpanded ? "false" : "true";
      expandButton.textContent = isExpanded ? "さらに表示" : "折りたたむ";
      return;
    }
    const imageButton = event.target.closest("[data-feed-image-url]");
    if (imageButton) {
      openImageLightbox(imageButton.dataset.feedImageUrl, imageButton.dataset.feedImageAlt);
      return;
    }
  });
  document.addEventListener("keydown", (event) => {
    if (event.key === "Escape") {
      document.querySelector(".feed-image-lightbox")?.classList.remove("is-open");
    }
  });
  stream.addEventListener("change", (event) => {
    const input = event.target.closest(".feed-image-upload");
    if (input) {
      uploadImage(input).catch((error) => NovelUI.toast(error.message || "画像アップロードに失敗しました。", "danger"));
    }
  });
  pagination?.addEventListener("click", (event) => {
    const stepButton = event.target.closest("[data-feed-page-step]");
    const numberButton = event.target.closest("[data-feed-page-number]");
    let nextPage = currentFeedPage;
    if (stepButton) {
      nextPage += Number(stepButton.dataset.feedPageStep || 0);
    } else if (numberButton) {
      nextPage = Number(numberButton.dataset.feedPageNumber || currentFeedPage);
    } else {
      return;
    }
    nextPage = Math.max(1, Math.min(currentPagination.total_pages || 1, nextPage));
    if (nextPage === currentFeedPage) return;
    loadFeed(nextPage)
      .then(() => window.scrollTo({ top: root.offsetTop || 0, behavior: "smooth" }))
      .catch((error) => NovelUI.toast(error.message || "読み込みに失敗しました。", "danger"));
  });

  loadProjects()
    .then(() => Promise.all([loadFeed(), loadRanking()]))
    .catch((error) => NovelUI.toast(error.message || "Feedの初期化に失敗しました。", "danger"));
})();
